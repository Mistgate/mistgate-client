// Writes src/brands.css: the logos of the services on the Routes tiles (Simple Icons, CC0), as masks for the design's
// own glyph class, so a logo takes the tile's colour like the symbol it replaces. `pnpm brands` after editing
// brands.json. A brand the set does not carry (its owner asked for removal) keeps the design's symbol.
import { readFileSync, writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';

const names = JSON.parse(readFileSync(new URL('./brands.json', import.meta.url), 'utf8'));
const css = [...new Set(Object.values(names))].sort().map((slug) => {
  const icon = icons['si' + slug[0].toUpperCase() + slug.slice(1)];
  if (!icon) throw new Error('no such icon: ' + slug);
  const svg = `<svg viewBox='0 0 24 24' xmlns='http://www.w3.org/2000/svg'><path d='${icon.path}'/></svg>`;
  return `.g-b-${slug}{--m:url("data:image/svg+xml,${svg.replace(/</g, '%3C').replace(/>/g, '%3E').replace(/#/g, '%23')}")}`;
});
writeFileSync(new URL('../src/brands.css', import.meta.url), '/* generated by tools/brands.mjs from Simple Icons (CC0); do not edit */\n' + css.join('\n') + '\n');
console.log(css.length + ' logos');
