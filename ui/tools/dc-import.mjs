// Turns the design canvas masters (design/project/*.dc.html) into what the app renders: the template (the markup inside
// <x-dc>), the logic class and the declared props. The design stays the source: re-run after the canvas changes.
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ui = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(ui, '..', 'design', 'project');
const out = join(ui, 'src', 'screens');
const MASTERS = ['Main', 'Routes', 'Diag', 'Settings', 'Tray', 'Setup', 'TrayIcons', 'Toasts', 'Brand'];
const blob = (s) => s.replace(/\/_blob\/([a-f0-9]{32})/g, '/blob/$1.svg');

for (const name of MASTERS) {
  const html = readFileSync(join(src, name + '.dc.html'), 'utf8');
  const body = html.match(/<x-dc>([\s\S]*?)<\/x-dc>/);
  const script = html.match(/<script type="text\/x-dc" data-dc-script data-props='([^']*)'>([\s\S]*?)<\/script>/);
  if (!body || !script) throw new Error(name + ': not a design component');
  const tpl = blob(body[1].replace(/<helmet>[\s\S]*?<\/helmet>/, '')).trim();
  writeFileSync(join(out, name + '.html'), tpl + '\n');
  writeFileSync(join(out, name + '.logic.js'),
    "// Generated by tools/dc-import.mjs from design/project/" + name + ".dc.html: do not edit here.\n" +
    "import { DCLogic } from '../dc';\n" + blob(script[2]).trim() + '\nexport default Component;\n');
  const props = JSON.parse(script[1].replace(/&#39;/g, "'").replace(/&amp;/g, '&'));
  writeFileSync(join(out, name + '.props.json'), JSON.stringify(props, null, 1) + '\n');
}
for (const css of ['app.css', 'app.fa.css', 'app.zh.css'])
  writeFileSync(join(ui, 'src', 'design', css), blob(readFileSync(join(src, css), 'utf8')));
copyFileSync(join(src, 'ds', 'mistgate', 'tokens.json'), join(ui, 'src', 'design', 'tokens.json'));
console.log('imported', MASTERS.length, 'masters');
