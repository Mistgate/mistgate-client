// Turns the design canvas masters (design/project/*.dc.html) into what the app renders: the template (the markup inside
// <x-dc>) and the logic class, per language. The design stays the source: re-run after the canvas changes.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ui = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(ui, '..', 'design', 'project');
const out = join(ui, 'src', 'screens');
const SCREENS = ['Main', 'Routes', 'Diag', 'Settings', 'Tray', 'Setup'];
const KITS = ['TrayIcons', 'Toasts', 'Brand']; // boards about the design itself: English only
const LANGS = { en: '', ru: 'Ru', fa: 'Fa', zh: 'Zh', tr: 'Tr' };
const blob = (s) => s.replace(/\/_blob\/([a-f0-9]{32})/g, '/blob/$1.svg');

let count = 0;
for (const [lang, prefix] of Object.entries(LANGS)) {
  mkdirSync(join(out, lang), { recursive: true });
  // a link to another screen names its file in this language; the app has one name per screen
  const link = prefix ? new RegExp('\\b' + prefix + '([A-Z][A-Za-z]*\\.dc\\.html)', 'g') : null;
  const local = (s) => (link ? blob(s).replace(link, '$1') : blob(s));
  for (const name of lang === 'en' ? [...SCREENS, ...KITS] : SCREENS) {
    const file = prefix + name + '.dc.html';
    const html = readFileSync(join(src, file), 'utf8');
    const body = html.match(/<x-dc>([\s\S]*?)<\/x-dc>/);
    const script = html.match(/<script type="text\/x-dc" data-dc-script data-props='[^']*'>([\s\S]*?)<\/script>/);
    if (!body || !script) throw new Error(file + ': not a design component');
    writeFileSync(join(out, lang, name + '.html'), local(body[1].replace(/<helmet>[\s\S]*?<\/helmet>/, '')).trim() + '\n');
    writeFileSync(join(out, lang, name + '.logic.js'),
      '// Generated by tools/dc-import.mjs from design/project/' + file + ': do not edit here.\n' +
      "import { DCLogic } from '../../dc';\n" + local(script[1]).trim() + '\nexport default Component;\n');
    count++;
  }
}
for (const css of ['app.css', 'app.fa.css', 'app.zh.css'])
  // the bundled fonts are the variable builds (one file set for every weight), named "… Variable"
  writeFileSync(join(ui, 'src', 'design', css), blob(readFileSync(join(src, css), 'utf8'))
    .replaceAll(',Vazirmatn,', ',"Vazirmatn Variable",').replaceAll('"Noto Sans SC"', '"Noto Sans SC Variable"'));
copyFileSync(join(src, 'ds', 'mistgate', 'tokens.json'), join(ui, 'src', 'design', 'tokens.json'));
console.log('imported', count, 'screens in', Object.keys(LANGS).length, 'languages');
